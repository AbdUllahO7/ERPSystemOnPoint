/**
 * Intelligent ERP phrase translator with regex and prefix patterns.
 *
 * @param {string} text
 * @param {string} [locale='ar']
 * @returns {string}
 */
export function translateErp(text, locale = "ar") {
  if (!text || typeof text !== "string" || locale !== "ar") {
    return text;
  }
  const trimmed = text.trim();
  if (!trimmed) return text;

  // 1. Direct dictionary match
  if (ERP_DICTIONARY[trimmed]) {
    return ERP_DICTIONARY[trimmed];
  }

  // 2. Case-insensitive exact match
  const lower = trimmed.toLowerCase();
  for (const [key, val] of Object.entries(ERP_DICTIONARY)) {
    if (key.toLowerCase() === lower) {
      return val;
    }
  }

  // 3. Trailing colon handling (e.g. "Category:", "Amount:")
  if (trimmed.endsWith(":")) {
    const withoutColon = trimmed.slice(0, -1).trim();
    const translated = translateErp(withoutColon, locale);
    if (translated !== withoutColon) {
      return translated + ":";
    }
  }

  // 4. "Search <X>..." pattern
  const searchMatch = trimmed.match(/^Search\s+(.+)\.{2,3}$/i);
  if (searchMatch) {
    const subject = searchMatch[1].trim();
    const translatedSub = translateErp(subject, locale);
    return translatedSub !== subject ? `البحث في ${translatedSub}...` : `بحث...`;
  }

  // 5. "Add <X>" pattern
  const addMatch = trimmed.match(/^Add\s+(.+)$/i);
  if (addMatch) {
    const subject = addMatch[1].trim();
    const translatedSub = translateErp(subject, locale);
    return `إضافة ${translatedSub}`;
  }

  // 6. "Edit <X>" pattern
  const editMatch = trimmed.match(/^Edit\s+(.+)$/i);
  if (editMatch) {
    const subject = editMatch[1].trim();
    const translatedSub = translateErp(subject, locale);
    return `تعديل ${translatedSub}`;
  }

  // 7. "Delete <X>" pattern
  const deleteMatch = trimmed.match(/^Delete\s+(.+)$/i);
  if (deleteMatch) {
    const subject = deleteMatch[1].trim();
    const translatedSub = translateErp(subject, locale);
    return `حذف ${translatedSub}`;
  }

  // 8. "Filter by <X>" pattern
  const filterMatch = trimmed.match(/^Filter\s+by\s+(.+)$/i);
  if (filterMatch) {
    const subject = filterMatch[1].trim();
    const translatedSub = translateErp(subject, locale);
    return `فلترة حسب ${translatedSub}`;
  }

  // 9. "All <X>" pattern
  const allMatch = trimmed.match(/^All\s+(.+)$/i);
  if (allMatch) {
    const subject = allMatch[1].trim();
    const translatedSub = translateErp(subject, locale);
    return `جميع ${translatedSub}`;
  }

  // 10. "Select <X>" pattern
  const selectMatch = trimmed.match(/^Select\s+(.+)$/i);
  if (selectMatch) {
    const subject = selectMatch[1].trim();
    const translatedSub = translateErp(subject, locale);
    return `حدد ${translatedSub}`;
  }

  // 11. "No <X> found" pattern
  const noMatch = trimmed.match(/^No\s+(.+)\s+found$/i);
  if (noMatch) {
    const subject = noMatch[1].trim();
    const translatedSub = translateErp(subject, locale);
    return `لا توجد ${translatedSub}`;
  }

  // 12. "<X> List" pattern
  const listMatch = trimmed.match(/^(.+)\s+List$/i);
  if (listMatch) {
    const subject = listMatch[1].trim();
    const translatedSub = translateErp(subject, locale);
    return `قائمة ${translatedSub}`;
  }

  return text;
}

/**
 * Translate column header label
 */
export function translateColumnHeader(col, locale = "ar") {
  if (!col) return col;
  const raw = typeof col.header === "string" ? col.header : col.label;
  if (typeof raw !== "string") return raw;
  return translateErp(raw, locale);
}

/**
 * Translate tabs (array or object)
 */
export function translateTabLabel(label, locale = "ar") {
  return translateErp(label, locale);
}

